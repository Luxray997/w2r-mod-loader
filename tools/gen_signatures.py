#!/usr/bin/env python3
"""Converts wc2r-plus's src/target/signatures.generated.h into a Rust table.

Usage: gen_signatures.py <signatures.generated.h> <out.rs> [--source "<describe origin>"]

The header defines `const uint8_t kSigX[] = {...};`, optional `const RelocSlot kRelX[] = {{off,
addr}, ...};` and one `kSignatures[]` array of `{"what", 0xaddr, kSigX, sizeof(kSigX), kRelX|nullptr,
count}` entries. The output is `pub static SIGNATURES: &[Signature]` for crates/w2r-core.
"""
import re
import sys

BYTES_RE = re.compile(r"const uint8_t (kSig\w+)\[\] = \{([^}]*)\};", re.S)
RELOCS_RE = re.compile(r"const RelocSlot (kRel\w+)\[\] = \{(.*?)\};", re.S)
PAIR_RE = re.compile(r"\{\s*(\d+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}")
BYTE_RE = re.compile(r"0x[0-9a-fA-F]{1,2}")
TABLE_RE = re.compile(r"kSignatures\[\]\s*=\s*\{(.*)\};", re.S)
ENTRY_RE = re.compile(
    r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(kSig\w+)\s*,\s*sizeof\(\3\)\s*,\s*'
    r"(kRel\w+|nullptr)\s*,",
    re.S,
)


class BadHeader(ValueError):
    pass


def parse(text):
    """Returns a list of dicts: what, static_addr, bytes, relocs=[(offset, static_addr)]."""
    byte_tables = {m.group(1): bytes(int(b, 16) for b in BYTE_RE.findall(m.group(2)))
                   for m in BYTES_RE.finditer(text)}
    reloc_tables = {m.group(1): [(int(o), int(a, 16)) for o, a in PAIR_RE.findall(m.group(2))]
                    for m in RELOCS_RE.finditer(text)}
    table = TABLE_RE.search(text)
    if not table:
        raise BadHeader("no kSignatures[] array")
    sigs = []
    for m in ENTRY_RE.finditer(table.group(1)):
        what, addr, sig_name, rel_name = m.groups()
        if sig_name not in byte_tables:
            raise BadHeader(f"{sig_name} referenced but not defined")
        data = byte_tables[sig_name]
        if not data:
            raise BadHeader(f"{sig_name} is empty")
        relocs = []
        if rel_name != "nullptr":
            if rel_name not in reloc_tables:
                raise BadHeader(f"{rel_name} referenced but not defined")
            relocs = reloc_tables[rel_name]
            for off, _ in relocs:
                if off + 4 > len(data):
                    raise BadHeader(f"{rel_name}: reloc at +{off} exceeds {len(data)} bytes")
        sigs.append({
            "what": what.encode().decode("unicode_escape"),
            "static_addr": int(addr, 16),
            "bytes": data,
            "relocs": relocs,
        })
    if not sigs:
        raise BadHeader("kSignatures[] has no entries")
    if len(sigs) != len(byte_tables):
        raise BadHeader(f"{len(byte_tables)} byte tables but {len(sigs)} table entries")
    return sigs


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(sigs, source):
    out = [
        "//! GENERATED by tools/gen_signatures.py. Do not edit; regenerate when the game updates.",
        f"//! Source: {source}",
        "//! Derived from wc2r-plus (MIT, Copyright (c) 2026 Luxray997); see THIRD_PARTY_NOTICES.md.",
        "",
        "use super::{RelocSlot, Signature};",
        "",
        f"pub const COUNT: usize = {len(sigs)};",
        "",
        "pub static SIGNATURES: &[Signature] = &[",
    ]
    for s in sigs:
        out.append("    Signature {")
        out.append(f"        what: {rust_str(s['what'])},")
        out.append(f"        static_addr: 0x{s['static_addr']:08x},")
        out.append("        bytes: &[")
        data = s["bytes"]
        for i in range(0, len(data), 12):
            out.append("            " + " ".join(f"0x{b:02x}," for b in data[i:i + 12]))
        out.append("        ],")
        if s["relocs"]:
            out.append("        relocs: &[")
            for off, addr in s["relocs"]:
                out.append(f"            RelocSlot {{ offset: {off}, static_addr: 0x{addr:08x} }},")
            out.append("        ],")
        else:
            out.append("        relocs: &[],")
        out.append("    },")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    source = "wc2r-plus src/target/signatures.generated.h"
    if "--source" in argv:
        source = argv[argv.index("--source") + 1]
    with open(argv[1], encoding="utf-8") as f:
        sigs = parse(f.read())
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write(emit(sigs, source))
    print(f"{len(sigs)} signatures, {sum(len(s['relocs']) for s in sigs)} reloc slots -> {argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
