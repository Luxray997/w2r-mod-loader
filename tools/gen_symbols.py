#!/usr/bin/env python3
"""Converts wc2r-plus's src/target/addresses.h into a Rust symbol table.

Usage: gen_symbols.py <addresses.h> <out.rs> [--source "<describe origin>"]

The header declares `using XFn = ret(__conv*)(args);` aliases, `constexpr Fun<XFn> kName{0xaddr};`
functions and `constexpr Obj<T> kName{0xaddr};` globals. The output is
`pub static SYMBOLS: &[Symbol]`, sorted by name, for crates/w2r-core.
"""
import re
import sys

PREFERRED_IMAGE_BASE = 0x00400000
SIZE_OF_IMAGE = 0x0062B000

USING_RE = re.compile(r"\busing\s+(\w+)\s*=\s*(.*?);", re.S)
FUN_RE = re.compile(r"constexpr\s+Fun<(\w+)>\s+k(\w+)\s*\{\s*(0x[0-9a-fA-F]+)\s*\};")
OBJ_RE = re.compile(r"constexpr\s+Obj<([^>]+)>\s+k(\w+)\s*\{\s*(0x[0-9a-fA-F]+)\s*\};")


class BadHeader(ValueError):
    pass


def parse(text):
    """Returns a list of dicts sorted by name: name, kind ("Function"|"Object"), static_addr, c_type."""
    aliases = {m.group(1): " ".join(m.group(2).split()) for m in USING_RE.finditer(text)}
    syms = []
    for m in FUN_RE.finditer(text):
        alias, name, addr = m.groups()
        if alias not in aliases:
            raise BadHeader(f"{name}: function type {alias} is not declared")
        syms.append({"name": name, "kind": "Function", "static_addr": int(addr, 16),
                     "c_type": aliases[alias]})
    for m in OBJ_RE.finditer(text):
        ctype, name, addr = m.groups()
        ctype = " ".join(ctype.split())
        syms.append({"name": name, "kind": "Object", "static_addr": int(addr, 16),
                     "c_type": aliases.get(ctype, ctype)})
    if not syms:
        raise BadHeader("no Fun<> or Obj<> declarations found")
    seen = set()
    for s in syms:
        if s["name"] in seen:
            raise BadHeader(f"duplicate symbol {s['name']}")
        seen.add(s["name"])
        rva = s["static_addr"] - PREFERRED_IMAGE_BASE
        if not 0 <= rva < SIZE_OF_IMAGE:
            raise BadHeader(f"{s['name']}: 0x{s['static_addr']:08x} is outside the image")
    syms.sort(key=lambda s: s["name"])
    return syms


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(syms, source):
    out = [
        "//! GENERATED by tools/gen_symbols.py. Do not edit; regenerate when the game updates.",
        f"//! Source: {source}",
        "//! Derived from wc2r-plus (MIT, Copyright (c) 2026 Luxray997); see THIRD_PARTY_NOTICES.md.",
        "",
        "use super::{Kind, Symbol};",
        "",
        f"pub const COUNT: usize = {len(syms)};",
        "",
        "/// Sorted by `name` (bytewise), so lookups can binary-search.",
        "pub static SYMBOLS: &[Symbol] = &[",
    ]
    for s in syms:
        out.append("    Symbol {")
        out.append(f"        name: {rust_str(s['name'])},")
        out.append(f"        kind: Kind::{s['kind']},")
        out.append(f"        static_addr: 0x{s['static_addr']:08x},")
        out.append(f"        c_type: {rust_str(s['c_type'])},")
        out.append("    },")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    source = "wc2r-plus src/target/addresses.h"
    if "--source" in argv:
        source = argv[argv.index("--source") + 1]
    with open(argv[1], encoding="utf-8") as f:
        syms = parse(f.read())
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write(emit(syms, source))
    funcs = sum(1 for s in syms if s["kind"] == "Function")
    print(f"{len(syms)} symbols ({funcs} functions, {len(syms) - funcs} objects) -> {argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
